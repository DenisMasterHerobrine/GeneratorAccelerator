package dev.denismasterherobrine.generatoraccelerator2.dfc;

import static org.junit.jupiter.api.Assertions.assertNotNull;

import dev.denismasterherobrine.generatoraccelerator2.dfc.codegen.PointProgram;
import dev.denismasterherobrine.generatoraccelerator2.dfc.codegen.ProgramCompiler;
import dev.denismasterherobrine.generatoraccelerator2.dfc.ir.Node;
import dev.denismasterherobrine.generatoraccelerator2.dfc.runtime.Ga2RandomState;
import dev.denismasterherobrine.generatoraccelerator2.dfc.runtime.ProgramSet;
import java.util.ArrayList;
import java.util.List;
import java.util.Random;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.registries.Registries;
import net.minecraft.data.registries.VanillaRegistries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.levelgen.DensityFunction;
import net.minecraft.world.level.levelgen.NoiseGeneratorSettings;
import net.minecraft.world.level.levelgen.RandomState;
import org.junit.jupiter.api.Test;

/** Generated bytecode must match the reference interpreter (and therefore vanilla) bit for bit. */
public class PointProgramTest {
    private static final List<ResourceKey<NoiseGeneratorSettings>> PRESETS = List.of(
        NoiseGeneratorSettings.OVERWORLD, NoiseGeneratorSettings.AMPLIFIED, NoiseGeneratorSettings.LARGE_BIOMES,
        NoiseGeneratorSettings.NETHER, NoiseGeneratorSettings.END, NoiseGeneratorSettings.CAVES, NoiseGeneratorSettings.FLOATING_ISLANDS);
    private static final int POINTS = 6000;

    @Test
    void generatedCodeMatchesInterpreter() {
        HolderLookup.Provider lookup = VanillaRegistries.createLookup();
        Random rng = new Random(0xBEEFL);
        long comparisons = 0;
        for (ResourceKey<NoiseGeneratorSettings> preset : PRESETS) {
            NoiseGeneratorSettings settings = lookup.lookupOrThrow(Registries.NOISE_SETTINGS).getOrThrow(preset).value();
            RandomState state = RandomState.create(settings, lookup.lookupOrThrow(Registries.NOISE), 987654321L);
            ProgramSet set = ((Ga2RandomState) (Object) state).ga2$programs();
            assertNotNull(set);
            List<String> names = new ArrayList<>();
            List<Node> roots = new ArrayList<>();
            set.routerRoots().forEach((k, v) -> { names.add(k); roots.add(v); });
            set.samplerRoots().forEach((k, v) -> { names.add(k); roots.add(v); });
            long t0 = System.nanoTime();
            PointProgram program = ProgramCompiler.compilePoint(preset.location().getPath(), roots, set.specs(), set.blendedSpecs());
            System.out.println("compiled point program for " + preset.location() + " in " + (System.nanoTime() - t0) / 1_000_000L + " ms, scratch=" + program.scratchSize);
            double[] scratch = new double[Math.max(1, program.scratchSize)];
            double[] out = new double[roots.size()];
            for (int i = 0; i < POINTS; i++) {
                int x, z;
                switch (rng.nextInt(4)) {
                    case 0 -> { x = rng.nextInt(60_000_000) - 30_000_000; z = rng.nextInt(60_000_000) - 30_000_000; }
                    case 1 -> { x = (rng.nextInt(2000) - 1000) * 4; z = (rng.nextInt(2000) - 1000) * 4; }
                    default -> { x = rng.nextInt(8192) - 4096; z = rng.nextInt(8192) - 4096; }
                }
                int y = rng.nextInt(3) == 0 ? -64 + rng.nextInt(49) * 8 : rng.nextInt(400) - 70;
                DensityFunction.SinglePointContext ctx = new DensityFunction.SinglePointContext(x, y, z);
                program.computeAll(ctx, scratch, out);
                for (int r = 0; r < roots.size(); r++) {
                    double expected = set.interpreter().eval(roots.get(r), ctx);
                    if (Double.doubleToRawLongBits(expected) != Double.doubleToRawLongBits(out[r])) {
                        throw new AssertionError(preset.location() + " root " + names.get(r) + " at (" + x + "," + y + "," + z + "): interpreter=" + expected + " generated=" + out[r]);
                    }
                    comparisons++;
                }
            }
        }
        System.out.println("DFC codegen: " + comparisons + " comparisons bit-identical");
    }
}
