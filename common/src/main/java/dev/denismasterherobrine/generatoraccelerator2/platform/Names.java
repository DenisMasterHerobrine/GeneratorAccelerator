package dev.denismasterherobrine.generatoraccelerator2.platform;

import dev.denismasterherobrine.generatoraccelerator2.Ga2Log;
import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayDeque;
import java.util.Deque;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.zip.GZIPInputStream;
import org.slf4j.Logger;

/**
 * Minecraft's names as the running game has them. GA2's code names vanilla classes and members by their Mojang names, in
 * inspection tables, reflection and generated bytecode. NeoForge runs the game under those names. Fabric runs it under
 * intermediary names ({@code net/minecraft/class_2791}, {@code method_12345}, {@code field_12345}). On Fabric the build ships
 * a table of the classes GA2 refers to, plus their supertypes, with their members. Everywhere else every method here
 * returns its input.
 *
 * <p>There are two directions. {@code runtime*} turns a Mojang name into the running game's name. {@code mojang*} turns a
 * name read from a loaded class back into its Mojang name, so a comparison with GA2's tables reads the same on both
 * loaders. Names the table does not know come back unchanged, e.g. other mods' classes, synthetic members and Mixin's
 * handlers.
 *
 * <p>Used by mixin plugins while classes are transformed, so this class uses no Minecraft types.
 */
public final class Names {
    private static final Logger LOGGER = Ga2Log.get("Names");
    private static final Table TABLE = load();

    private Names() {}

    /** The table resource the Fabric build writes. It holds gzipped lines (see {@link Table#read}). */
    public static final String RESOURCE = "generatoraccelerator2/mappings.txt.gz";

    private static Table load() {
        InputStream in;
        try {
            in = Platform.openNameTable();
        } catch (LinkageError | IllegalStateException e) {
            // No platform module (unit tests of the common code). Use Mojang names.
            return null;
        }
        if (in == null) {
            return null;
        }
        try (in) {
            Table t = Table.read(in);
            LOGGER.debug("loaded {} class names", t.toRuntimeClass.size());
            return t;
        } catch (IOException e) {
            throw new IllegalStateException("Could not read GA2's Minecraft name table", e);
        }
    }

    /** True when the game runs under Mojang names. Every method here is then the identity. */
    public static boolean mojang() {
        return TABLE == null;
    }

    // ---- Mojang -> runtime ----

    /** A class's internal name ({@code net/minecraft/world/level/chunk/ChunkAccess}) in the running game. */
    public static String runtimeClass(String internalName) {
        return TABLE == null ? internalName : TABLE.toRuntimeClass.getOrDefault(internalName, internalName);
    }

    /** A class's binary name ({@code net.minecraft.world.level.chunk.ChunkAccess}) in the running game. */
    public static String runtimeBinaryClass(String binaryName) {
        return TABLE == null ? binaryName : runtimeClass(binaryName.replace('.', '/')).replace('/', '.');
    }

    /** A field or method descriptor with its classes renamed for the running game. */
    public static String runtimeDesc(String desc) {
        return TABLE == null ? desc : mapDesc(desc, TABLE.toRuntimeClass);
    }

    /** A method's name in the running game, looked up in {@code owner} and its supertypes. */
    public static String runtimeMethod(String owner, String name, String desc) {
        if (TABLE == null) {
            return name;
        }
        String found = TABLE.findInHierarchy(owner, TABLE.methods, name + desc);
        return found != null ? found : name;
    }

    /**
     * A method's name in the running game, without its descriptor. Returns the names of every method called {@code name} in
     * {@code owner} and its supertypes. There is more than one name when such overloads map to different names.
     */
    public static Set<String> runtimeMethods(String owner, String name) {
        if (TABLE == null) {
            return Set.of(name);
        }
        Set<String> out = new HashSet<>();
        TABLE.forHierarchy(owner, cls -> {
            Map<String, String> members = TABLE.methods.get(cls);
            if (members != null) {
                for (Map.Entry<String, String> e : members.entrySet()) {
                    String key = e.getKey();
                    if (key.startsWith(name) && key.length() > name.length() && key.charAt(name.length()) == '(') {
                        out.add(e.getValue());
                    }
                }
            }
        });
        if (out.isEmpty()) {
            out.add(name);
        }
        return out;
    }

    /** A method's name and descriptor ({@code "name(desc)ret"}, as GA2's tables write them) in the running game. */
    public static String runtimeMethodKey(String owner, String key) {
        if (TABLE == null) {
            return key;
        }
        int paren = key.indexOf('(');
        if (paren < 0) {
            return key;
        }
        String name = key.substring(0, paren);
        String desc = key.substring(paren);
        return runtimeMethod(owner, name, desc) + runtimeDesc(desc);
    }

    /** A field's name in the running game, looked up in {@code owner} and its supertypes. */
    public static String runtimeField(String owner, String name) {
        if (TABLE == null) {
            return name;
        }
        String found = TABLE.findInHierarchy(owner, TABLE.fields, name);
        return found != null ? found : name;
    }

    // ---- runtime -> Mojang ----

    /** The Mojang internal name of a class read from the running game. */
    public static String mojangClass(String internalName) {
        return TABLE == null ? internalName : TABLE.toMojangClass.getOrDefault(internalName, internalName);
    }

    /** The Mojang binary name of a class read from the running game. */
    public static String mojangBinaryClass(String binaryName) {
        return TABLE == null ? binaryName : mojangClass(binaryName.replace('.', '/')).replace('/', '.');
    }

    /** A loaded class's Mojang binary name, for messages. {@code getName()} returns the running game's name. */
    public static String mojangName(Class<?> type) {
        return mojangBinaryClass(type.getName());
    }

    /** A loaded class's Mojang simple name, for messages. {@code getSimpleName()} returns the running game's name. */
    public static String mojangSimpleName(Class<?> type) {
        if (TABLE == null) {
            return type.getSimpleName();
        }
        String name = mojangName(type);
        return name.substring(Math.max(name.lastIndexOf('.'), name.lastIndexOf('$')) + 1);
    }

    /** A descriptor read from the running game, with its classes given their Mojang names. */
    public static String mojangDesc(String desc) {
        return TABLE == null ? desc : mapDesc(desc, TABLE.toMojangClass);
    }

    /** The Mojang name of a method read from the running game. Intermediary method names are unique, so no owner is needed. */
    public static String mojangMethod(String name) {
        return TABLE == null ? name : TABLE.toMojangMethod.getOrDefault(name, name);
    }

    /** {@code mojangMethod(name) + mojangDesc(desc)}. Keys a method read from the running game as GA2's tables key it. */
    public static String mojangMethodKey(String name, String desc) {
        return TABLE == null ? name + desc : mojangMethod(name) + mojangDesc(desc);
    }

    /** The Mojang name of a field read from the running game. */
    public static String mojangField(String name) {
        return TABLE == null ? name : TABLE.toMojangField.getOrDefault(name, name);
    }

    private static String mapDesc(String desc, Map<String, String> classes) {
        StringBuilder out = null;
        int i = 0;
        int copied = 0;
        while (i < desc.length()) {
            if (desc.charAt(i) != 'L') {
                i++;
                continue;
            }
            int end = desc.indexOf(';', i);
            if (end < 0) {
                break;
            }
            String cls = desc.substring(i + 1, end);
            String mapped = classes.get(cls);
            if (mapped != null) {
                if (out == null) {
                    out = new StringBuilder(desc.length() + 16);
                }
                out.append(desc, copied, i + 1).append(mapped);
                copied = end;
            }
            i = end + 1;
        }
        if (out == null) {
            return desc;
        }
        return out.append(desc, copied, desc.length()).toString();
    }

    /**
     * The name table, as tab-separated lines. A class line is {@code c <mojang> <runtime> [<mojang supertype>...]}. The lines
     * for the class's members follow it: {@code m <mojang name+desc> <runtime name>} and {@code f <mojang name> <runtime name>}.
     */
    static final class Table {
        final Map<String, String> toRuntimeClass = new HashMap<>();
        final Map<String, String> toMojangClass = new HashMap<>();
        final Map<String, List<String>> supers = new HashMap<>();
        /** Per Mojang class: Mojang name + descriptor to runtime name. */
        final Map<String, Map<String, String>> methods = new HashMap<>();
        /** Per Mojang class: Mojang name to runtime name. */
        final Map<String, Map<String, String>> fields = new HashMap<>();
        final Map<String, String> toMojangMethod = new HashMap<>();
        final Map<String, String> toMojangField = new HashMap<>();

        static Table read(InputStream raw) throws IOException {
            Table t = new Table();
            try (BufferedReader in = new BufferedReader(new InputStreamReader(new GZIPInputStream(raw), StandardCharsets.UTF_8))) {
                String cls = null;
                for (String line; (line = in.readLine()) != null; ) {
                    String[] p = line.split("\t");
                    switch (p[0]) {
                        case "c" -> {
                            cls = p[1];
                            t.toRuntimeClass.put(p[1], p[2]);
                            t.toMojangClass.put(p[2], p[1]);
                            if (p.length > 3) {
                                t.supers.put(cls, List.of(p).subList(3, p.length));
                            }
                        }
                        case "m" -> {
                            t.methods.computeIfAbsent(cls, k -> new HashMap<>()).put(p[1], p[2]);
                            int paren = p[1].indexOf('(');
                            t.toMojangMethod.putIfAbsent(p[2], p[1].substring(0, paren));
                        }
                        case "f" -> {
                            t.fields.computeIfAbsent(cls, k -> new HashMap<>()).put(p[1], p[2]);
                            t.toMojangField.putIfAbsent(p[2], p[1]);
                        }
                        default -> {
                        }
                    }
                }
            }
            return t;
        }

        String findInHierarchy(String owner, Map<String, Map<String, String>> members, String key) {
            String[] found = new String[1];
            forHierarchy(owner, cls -> {
                if (found[0] == null) {
                    Map<String, String> m = members.get(cls);
                    if (m != null) {
                        found[0] = m.get(key);
                    }
                }
            });
            return found[0];
        }

        void forHierarchy(String owner, java.util.function.Consumer<String> action) {
            Deque<String> queue = new ArrayDeque<>();
            Set<String> seen = new HashSet<>();
            queue.add(owner);
            while (!queue.isEmpty()) {
                String cls = queue.poll();
                if (!seen.add(cls)) {
                    continue;
                }
                action.accept(cls);
                queue.addAll(supers.getOrDefault(cls, List.of()));
            }
        }
    }
}
